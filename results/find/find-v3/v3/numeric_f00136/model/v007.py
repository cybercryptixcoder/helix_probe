def predict(probe):
    # Beliefs (revised after E16):
    # - The far field is a smooth, nearly-linear curve on each side, but with
    #   slight curvature; piecewise-linear interpolation through dense sweep
    #   points [E10,E14,E16] captures it well.
    # - Left far field (x<=-12): rises from ~0.0156 at x=-13 toward ~0.048 at -128.
    # - Right far field (x>=12): rises from ~-0.0187 at x=13 toward ~0.0565 at 128.
    # - Core |x|<12: sharp structure. Left lobe rises from ~0.019 at x=-12 to
    #   peak ~0.078 at x=-2..-1.5, then falls steeply to ~0 at x=0 [E2,E4,E6,E8,E12].
    # - Right lobe: from ~0 at x=0 falls to trough ~-0.095 at x=1, then rises
    #   back toward -0.021 at x=12 [E2,E4,E6,E8,E12].
    # - Core and far-field agree at |x|=12, so no discontinuity.
    # - Noisy; outputs approximate.

    x = probe["x"]
    return {"y": [_f(v) for v in x]}


def _interp(pts, x):
    if x <= pts[0][0]:
        x0, y0 = pts[0]; x1, y1 = pts[1]
        return y0 + (x - x0) * (y1 - y0) / (x1 - x0)
    if x >= pts[-1][0]:
        x0, y0 = pts[-2]; x1, y1 = pts[-1]
        return y1 + (x - x1) * (y1 - y0) / (x1 - x0)
    for i in range(len(pts) - 1):
        x0, y0 = pts[i]; x1, y1 = pts[i+1]
        if x0 <= x <= x1:
            return y0 + (x - x0) * (y1 - y0) / (x1 - x0)
    return 0.0


