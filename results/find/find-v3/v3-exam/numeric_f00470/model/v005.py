# Model of the black box.
#
# Beliefs:
# - For |x| >= 1, f is a smooth polynomial (degree 5 fits the data essentially
#   exactly on both sides; the two sides differ in coefficients). [E1-E19]
# - For |x| < 1, f is a *different* smooth function, and the two sides are
#   DIFFERENT polynomials meeting at x=0 (not one shared polynomial). [E22, E24]
# - The small-|x| region is NOT a low-degree polynomial in x; the values wiggle
#   non-monotonically (e.g. -0.001 -> 22.3, -0.005 -> 20.4, -0.05 -> 21.6,
#   -0.15 -> 24.0, -0.25 -> 29.8, -0.35 -> 26.7 ...). This looks like a
#   high-frequency / oscillatory component, e.g. sin(k*x) or a high-degree
#   polynomial. [E16, E18, E20, E22, E24]
# - Positive side small-x: values at 0.01..0.9 (E16/E18) and 0.05..0.85 (E22)
#   are consistent with each other. Negative side small-x: E20/E22/E24 give
#   a different curve. So two separate piecewise polynomials on (-1,0) and
#   (0,1), plus a jump at |x|=1 into the power-law region.
#
# Strategy: fit high-degree polynomials to the small-|x| data on each side
# separately (degree 12 to capture the wiggles), and degree-5 to |x|>=1.
# The wiggles are the key thing v4 missed.

def _solve(A, b):
    n = len(A)
    M = [row[:] + [b[i]] for i, row in enumerate(A)]
    for i in range(n):
        p = max(range(i, n), key=lambda r: abs(M[r][i]))
        M[i], M[p] = M[p], M[i]
        if abs(M[i][i]) < 1e-15:
            continue
        for j in range(i+1, n):
            f = M[j][i] / M[i][i]
            for k in range(i, n+1):
                M[j][k] -= f * M[i][k]
    x = [0.0]*n
    for i in range(n-1, -1, -1):
        if abs(M[i][i]) < 1e-15:
            x[i] = 0.0
        else:
            s = M[i][n] - sum(M[i][j]*x[j] for j in range(i+1, n))
            x[i] = s / M[i][i]
    return x

def _polyfit(xs, ys, deg):
    n = deg+1
    A = [[0.0]*n for _ in range(n)]
    b = [0.0]*n
    for x, y in zip(xs, ys):
        pw = [x**k for k in range(2*deg+1)]
        for i in range(n):
            for j in range(n):
                A[i][j] += pw[i+j]
            b[i] += y * pw[i]
    return _solve(A, b)

def _eval(coef, x):
    s = 0.0
    for c in reversed(coef):
        s = s*x + c
    return s

