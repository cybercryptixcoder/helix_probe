def predict(probe):
    # Beliefs:
    # - |x|>=1: degree-5 polynomial, separate for x>=1 and x<=-1. [E1-E19]
    # - 0<=x<1: separate degree-12 polynomial (wiggly). [E16,E18,E22]
    # - -1<x<0: separate degree-12 polynomial (wiggly). [E20,E22,E24]
    # - jump at |x|=1 into power-law region. [E4,E6,E12]
    xs = probe["x"]
    ys = []
    for x in xs:
        if x is None:
            ys.append(None)
            continue
        try:
            x = float(x)
        except Exception:
            ys.append(None)
            continue
        if math.isnan(x) or math.isinf(x):
            ys.append(None)
            continue
        if x >= 1.0:
            y = _eval(_pos_coef, x)
        elif x <= -1.0:
            y = _eval(_neg_coef, x)
        elif x >= 0.0:
            y = _eval(_posin_coef, x)
        else:
            y = _eval(_negin_coef, x)
        ys.append(y)
    return {"y": ys}
