import math

def predict(probe):
    # anchor points for the main bump, from observations
    right_pts = [
        (0.0, 0.389), (0.4, 0.3361), (0.5, 0.3225), (0.6, 0.309), (0.7, 0.2955),
        (0.8, 0.282), (0.9, 0.2685), (1.0, 0.255), (1.1, 0.2415), (1.2, 0.228),
        (1.35, 0.2078), (1.45, 0.1943), (1.6, 0.174), (1.7, 0.1605), (1.85, 0.1402),
        (1.95, 0.1267), (2.05, 0.1132), (2.25, 0.089), (2.45, 0.0692), (2.65, 0.0508),
        (2.85, 0.038), (3.05, 0.031), (3.25, 0.0244), (3.45, 0.0194), (3.75, 0.0134),
        (4.0, 0.0099), (4.4, 0.0043), (4.8, 0.0014), (5.2, 0.001), (5.6, 0.0005),
        (7.0, 0.0), (10.0, 0.0)
    ]
    left_pts = [
        (0.0, 0.389), (0.5, 0.3052), (0.6, 0.2836), (0.7, 0.262), (0.8, 0.2404),
        (0.9, 0.2188), (1.0, 0.1972), (1.1, 0.1756), (1.2, 0.1552), (1.35, 0.1301),
        (1.45, 0.1135), (1.55, 0.0985), (1.65, 0.0862), (1.75, 0.078), (1.85, 0.0698),
        (1.95, 0.0616), (2.05, 0.0534), (2.15, 0.0452), (2.25, 0.037), (2.35, 0.0288),
        (2.45, 0.0242), (2.55, 0.0199), (2.7, 0.0133), (2.9, 0.0082), (3.1, 0.0077),
        (3.3, 0.0072), (3.6, 0.0064), (4.0, 0.0053), (4.5, 0.004), (6.0, 0.002),
        (7.0, 0.0), (10.0, 0.0)
    ]

    def interp(pts, x):
        if x <= pts[0][0]:
            return pts[0][1]
        if x >= pts[-1][0]:
            return pts[-1][1]
        for i in range(len(pts) - 1):
            x0, y0 = pts[i]
            x1, y1 = pts[i + 1]
            if x0 <= x <= x1:
                t = (x - x0) / (x1 - x0)
                return y0 + t * (y1 - y0)
        return pts[-1][1]

    out = []
    for x in probe.get("x", []):
        try:
            x = float(x)
            if x >= 0:
                y = interp(right_pts, x)
                y += -0.0061 * math.exp(-((x - 12.0) ** 2) / (2 * 4.0 * 4.0))
                y += -0.0030 * math.exp(-((x - 18.0) ** 2) / (2 * 3.0 * 3.0))
                y += -0.0004 * (1.0 - math.exp(-max(0.0, x - 20.0) / 8.0))
            else:
                ax = -x
                y = interp(left_pts, ax)
                y += -0.0005 * math.exp(-((ax - 12.0) ** 2) / (2 * 4.0 * 4.0))
                y += -0.0010 * math.exp(-((ax - 18.0) ** 2) / (2 * 3.0 * 3.0))
                if ax > 22.0:
                    y += -0.0014 - (ax - 22.0) * (0.0030 / 106.0)
                else:
                    y += -0.0014 * (1.0 - math.exp(-max(0.0, ax - 20.0) / 8.0))
            out.append(y)
        except Exception:
            out.append(None)
    return {"y": out}
