def _f(x):
    if x <= -2.0:
        return _interp_neg(x)
    if x >= 2.0:
        return _base(x)
    # (-2, 2): base plus anomaly on [0, 2]
    y = _base(x)
    if 0.0 <= x <= 2.0:
        y += _interp_g(x)
    return y
