                    # 0.75p+0.5625q+0.421875r = -1.3675-5.4186 = -6.7861
                    # p+q+r = -5.3245-5.4186 = -10.7431
                    # From eq1: p = -6.6008 - 0.5q - 0.25r
                    # eq2: 0.75(-6.6008-0.5q-0.25r)+0.5625q+0.421875r = -6.7861
                    #  -4.9506 -0.375q -0.1875r +0.5625q+0.421875r = -6.7861
                    #  0.1875q + 0.234375r = -1.8355
                    # eq3: -6.6008-0.5q-0.25r + q + r = -10.7431
                    #  0.5q + 0.75r = -4.1423
                    # From eq3: q = -8.2846 - 1.5r
                    # sub: 0.1875(-8.2846-1.5r)+0.234375r = -1.8355
                    #  -1.55336 -0.28125r +0.234375r = -1.8355
                    #  -0.046875r = -0.28214 => r = 6.019
