import math

def predict(probe):
    # Observed: y defined for x in roughly (-10, 128]; null for x <= about -10 [E1]
    # y grows with x; looks like sqrt or log-ish. Test: sqrt(x+10)?
    #   x=88.2 -> sqrt(98.2)=9.9 (no). Try sqrt(x)+? 
    #   x=2.9 -> 1.8914 ; x=21.3 -> 20.0415 ; x=66 -> 30.3358 ; x=72.7 -> 31.2158 ; x=88.2 -> 32.975
    # Differences: from 66->72.7 (6.7) y +0.88 ; 72.7->88.2 (15.5) y +1.76 -> slope ~0.115
    # 21.3->66 (44.7) y +10.29 -> slope ~0.23. Not linear.
    # Try y = sqrt(a*x+b):
    #   2.9: 1.8914^2=3.577 ; 21.3: 20.0415^2=401.66 ; 66: 30.3358^2=920.26
    #   Fit: (3.577-401.66)/(2.9-21.3)=398.08/18.4=21.63 -> a~21.6? then b=3.577-21.6*2.9=-59.1
    #   check 66: 21.6*66-59.1=1366.5 sqrt=36.9 (no)
    # Try y = a*sqrt(x)+b: sqrt(2.9)=1.703, sqrt(21.3)=4.615, sqrt(66)=8.124, sqrt(72.7)=8.526, sqrt(88.2)=9.392
    #   slope (30.3358-20.0415)/(8.124-4.615)=10.294/3.509=2.934
    #   (32.975-30.3358)/(9.392-8.124)=2.639/1.268=2.081  not constant
    # Try y = a*x^p: log-log
    #   ln y vs ln x: (ln2.9=1.065,ln1.8914=0.637),(ln21.3=3.059,ln20.0415=2.998)
    #   slope=(2.998-0.637)/(3.059-1.065)=2.361/1.994=1.184
    #   (ln66=4.190,ln30.3358=3.412): slope=(3.412-2.998)/(4.190-3.059)=0.414/1.131=0.366
    #   not power law
    # Try y = a*ln(x)+b:
    #   ln2.9=1.065->1.8914 ; ln21.3=3.059->20.0415 ; slope=18.15/1.994=9.10
    #   ln66=4.190: 1.8914+9.10*(4.190-1.065)=1.8914+28.44=30.33 ✓ (obs 30.3358!)
    #   ln72.7=4.286: 1.8914+9.10*(4.286-1.065)=1.8914+29.31=31.20 ✓ (obs 31.2158)
    #   ln88.2=4.480: 1.8914+9.10*(4.480-1.065)=1.8914+31.08=32.97 ✓ (obs 32.975)
    # So y = 9.10*ln(x) + b, with b = 1.8914 - 9.10*1.065 = 1.8914-9.69 = -7.80
    #   Check: 9.10*ln(x) - 7.80
    #   x=2.9: 9.10*1.0647-7.80=9.689-7.80=1.889 ✓
    #   x=21.3: 9.10*3.0587-7.80=27.834-7.80=20.034 ✓ (obs 20.0415)
    #   x=66: 9.10*4.1897-7.80=38.126-7.80=30.326 ✓
    # Refine: use two points exactly: (2.9,1.8914),(88.2,32.975)
    #   a=(32.975-1.8914)/(ln88.2-ln2.9)=31.0836/(4.4797-1.0647)=31.0836/3.4150=9.102
    #   b=1.8914-9.102*1.0647=1.8914-9.691=-7.799
    # So y = 9.102*ln(x) - 7.799 for x>0 (defined region)
    # Null for x<=0? But -6.0, -20.3, -24.3, -50.4, -61.7 all null. 2.9 positive works.
    # Hypothesis: y = 9.102*ln(x) - 7.799 for x>0, null for x<=0.
    # (ln undefined for x<=0 -> null makes sense)
    out = []
    for x in probe["x"]:
        try:
            if x is None or x <= 0:
                out.append(None)
            else:
                out.append(9.102*math.log(x) - 7.799)
        except Exception:
            out.append(None)
    return {"y": out}
