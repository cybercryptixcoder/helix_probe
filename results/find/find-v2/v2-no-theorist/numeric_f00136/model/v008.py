def predict(probe):
    # Beliefs about f, from the evidence:
    # Smooth asymmetric function. Central structure near 0, slowly rising tails.
    #
    # Central region (|x| < ~4.5) [E14, E24]:
    #   Positive bump: plateau ~0.078 for x in [-2.75,-0.9], peak ~0.0784 near -2,
    #     falls: -0.6->0.0626, -0.4->0.0372, -0.3->0.0277, -0.2->0.0182,
    #     -0.05->0.0039, 0.05->-0.0056, 0.2->-0.0199, 0.4->-0.0389, 0.6->-0.0622.
    #   Negative trough: min ~-0.0932 at x~1.1, 0.9->-0.0928, 1.4->-0.082,
    #     1.75->-0.0686, 2.25->-0.0551, 3->-0.0466, 4->-0.0438.
    #   Zero crossing near x=0.0 (between -0.05 and 0.05).
    #
    # Positive side mid (4.5 < x < ~21.5) [E12,E18,E20]:
    #   4.5->-0.0423, 5->-0.0405, 6->-0.0371, 8->-0.03, 10->-0.0249,
    #   12->-0.0208, 14->-0.0167, 16->-0.0126, 18->-0.0084, 18.5->-0.0074,
    #   19->-0.0064, 20->-0.0043, 21->-0.0023, 21.5->-0.0012, 22->-0.0008.
    #   Nearly linear slope ~0.0021/unit; zero crossing ~22.4.
    #
    # Positive side (22 < x < 30) [E16,E22]:
    #   22->-0.0008, 24->0.0003, 26->0.0014, 28->0.0025, 30->0.0035.
    #   Slope ~0.00055/unit.
    #
    # Positive side (30 < x < 65) [E22,E16]:
    #   30->0.0035, 32->0.0046, 34->0.0057, 36->0.0068, 38->0.0078, 40->0.0089,
    #   42->0.01, 44->0.0111, 45->0.0116, 46->0.0122, 48->0.0133, 50->0.0143,
    #   55->0.0171, 60->0.0198, 65->0.0225. Slope ~0.00055/unit.
    #
    # Positive far tail (x > 65) [E10,E19]:
    #   100->0.0415, 120->0.0522. Slope ~0.00054/unit.
    #
    # Negative side mid (4.5 < |x| < ~30) [E8]:
    #   -6->0.0471, -8->0.031, -10->0.0249, -12->0.0187, -16->0.0149,
    #   -20->0.0162, -24->0.0174, -30->0.0191. Dips to min ~0.0149 near |x|=16.
    #
    # Negative far tail (|x| > 30) [E10]:
    #   45->0.0233, 50->0.0248, 60->0.0277, 100->0.0394, 120->0.0455.
    #   Slope ~0.0003/unit.
    #
    xs = probe.get("x", [])
    ys = []
    for x in xs:
        try:
            x = float(x)
            if x < 0:
                ax = -x
                if ax <= 4.5:
                    y = central(x)
                elif ax <= 16.0:
                    y = 0.0471 + (ax - 6.0) * ((0.0149 - 0.0471) / 10.0)
                elif ax <= 30.0:
                    y = 0.0149 + (ax - 16.0) * ((0.0191 - 0.0149) / 14.0)
                else:
                    y = 0.0191 + (ax - 30.0) * ((0.0455 - 0.0191) / 90.0)
            else:
                if x <= 4.5:
                    y = central(x)
                elif x <= 22.0:
                    y = -0.0423 + (x - 4.5) * ((0.0423 - 0.0008) / 17.5)
                elif x <= 30.0:
                    y = -0.0008 + (x - 22.0) * ((0.0035 + 0.0008) / 8.0)
                elif x <= 65.0:
                    y = 0.0035 + (x - 30.0) * ((0.0225 - 0.0035) / 35.0)
                else:
                    y = 0.0225 + (x - 65.0) * ((0.0522 - 0.0225) / 55.0)
        except Exception:
            y = None
        ys.append(y)
    return {"y": ys}


def central(x):
    # Piecewise-linear interpolation of the central shape from E14/E24.
    pts = [
        (-4.5, -0.0438), (-4.0, -0.0438), (-3.0, -0.0466), (-2.75, 0.0725),
        (-2.25, 0.0764), (-2.0, 0.0784), (-1.75, 0.0783), (-1.25, 0.0778),
        (-0.9, 0.0775), (-0.6, 0.0626), (-0.4, 0.0372), (-0.3, 0.0277),
        (-0.2, 0.0182), (-0.05, 0.0039), (0.05, -0.0056), (0.2, -0.0199),
        (0.4, -0.0389), (0.6, -0.0622), (0.9, -0.0928), (1.1, -0.0932),
        (1.4, -0.082), (1.75, -0.0686), (2.25, -0.0551), (3.0, -0.0466),
        (4.0, -0.0438), (4.5, -0.0423),
    ]
    # Note: the -3.0 -> -2.75 jump in the data is an artifact of the bump edge;
    # treat -3.0 as 0.0706 and -2.75 as 0.0725 (from E24).
    pts[2] = (-3.0, 0.0706)
    if x <= pts[0][0]:
        return pts[0][1]
    if x >= pts[-1][0]:
        return pts[-1][1]
    for i in range(len(pts) - 1):
        x0, y0 = pts[i]
        x1, y1 = pts[i + 1]
        if x0 <= x <= x1:
            t = (x - x0) / (x1 - x0)
            return y0 + t * (y1 - y0)
    return pts[-1][1]
