def _interp(table, x):
    if x <= table[0][0]:
        (x0, y0), (x1, y1) = table[0], table[1]
        return y0 + (y1 - y0) * (x - x0) / (x1 - x0)
    if x >= table[-1][0]:
        (x0, y0), (x1, y1) = table[-2], table[-1]
        return y1 + (y1 - y0) * (x - x1) / (x1 - x0)
    lo, hi = 0, len(table) - 1
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if table[mid][0] <= x:
            lo = mid
        else:
            hi = mid
    x0, y0 = table[lo]
    x1, y1 = table[hi]
    return y0 + (y1 - y0) * (x - x0) / (x1 - x0)


