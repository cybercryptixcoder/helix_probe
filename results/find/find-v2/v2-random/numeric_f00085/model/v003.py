    # log-log fit: ln(y-c) = ln A + p ln|x|
    n=len(pts); sx=sy=sxx=sxy=0.0
    for ax,dy in pts:
        if dy<=0: continue
        lx=math.log(ax); ly=math.log(dy)
        sx+=lx; sy+=ly; sxx+=lx*lx; sxy+=lx*ly
    p=(n*sxy-sx*sy)/(n*sxx-sx*sx)
    lnA=(sy-p*sx)/n
    A=math.exp(lnA)
    r=10.0
    out=[]
    for x in probe["x"]:
        if x is None:
            out.append(None); continue
        ax=abs(x)
        if ax<r:
            out.append(c)
        else:
            out.append(c+A*(ax**p))
    return {"y": out}
