def _interp(pts, x):
    if x <= pts[0][0]:
        return pts[0][1]
    if x >= pts[-1][0]:
        (x0, y0), (x1, y1) = pts[-2], pts[-1]
        return y1 + (y1 - y0) * (x - x1) / (x1 - x0)
    lo, hi = 0, len(pts) - 1
    while hi - lo > 1:
        mid = (lo + hi) // 2
        if pts[mid][0] <= x:
            lo = mid
        else:
            hi = mid
    x0, y0 = pts[lo]
    x1, y1 = pts[hi]
    return y0 + (y1 - y0) * (x - x0) / (x1 - x0)


def predict(probe):
    try:
        xs = probe["x"]
        out = []
        for x in xs:
            try:
                x = float(x)
            except Exception:
                out.append(None)
                continue
            if x >= 0:
                if x < 50.8:
                    out.append(DEAD)
                else:
                    out.append(_interp(_pos, x))
            else:
                a = -x
                if a < 51.25:
                    out.append(DEAD)
                else:
                    out.append(_interp(_neg, a))
        return {"y": out}
    except Exception:
        return {"y": []}
